alter table public.platform_settings alter column mfa_required_admins set default false;

update public.platform_settings set mfa_required_admins = false where id;

comment on column public.platform_settings.mfa_required_admins
  is 'إلزام التحقق بخطوتين على مدير المشروع والمنسقين — يفتحه المدير من شاشة الحسابات الإدارية (ملاحظة ١٠٥)';
