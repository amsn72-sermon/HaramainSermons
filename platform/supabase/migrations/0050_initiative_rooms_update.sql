-- =====================================================================
-- 0050 — تحديث «عن المبادرة» بما استجدّ في القاعات والحسابات
--   (ملاحظات ١٧١–١٧٧): الدخول داخل المنصة وغرفة الانتظار وإشعار الطارقين،
--   وقاعات كل فريق، وقائمة صلاحيات الحساب الإداري، وإلزام التحقق لحساب،
--   والمرشد المتميّز، وباب التسجيل.
--   ولا يُذكر فيها شيء مالي ولا تسعيرة، ولا مكان الاستضافة.
-- =====================================================================

do $$
declare v jsonb; v_s jsonb; v_id text; v_blocks jsonb; v_new jsonb := '[]'::jsonb;
begin
  select content into v from public.page_content where key = 'initiative';
  if v is null then return; end if;

  for v_s in select jsonb_array_elements(v -> 'sections') loop
    v_id := v_s ->> 0;
    v_blocks := v_s -> 2;

    -- القاعات: الدخول من المنصة، وغرفة الانتظار، وقاعات كل فريق
    if v_id = 'rooms' and not (v_blocks::text like '%غرفة الانتظار%') then
      v_blocks := v_blocks || jsonb_build_array(
        jsonb_build_array('h3', 'الدخول من المنصة، والإذن بيد المنسق'),
        jsonb_build_array('p', 'تُفتح الجلسة داخل المنصة نفسها لا في نافذةٍ خارجية، ويدخلها العضو '
          || 'باسمه كما هو مسجَّل عندنا — فلا يُسأل عن اسم ولا يكتب غيره ولا يُغيّره. '
          || 'وتُفعَّل غرفة الانتظار تلقائيًّا متى دخل المنسق أو مدير المشروع.'),
        jsonb_build_array('p', 'وكل من يطلب الدخول يصل المنسق إشعارٌ باسمه في بطاقة «طلبات الدخول» '
          || 'أعلى الجلسة، ومعه بيانٌ أمِن المدعوّين هو أم لا — فيقبله أو يردّه. '
          || 'والقبول والردّ للمنسق ومدير المشروع وحدهما.'),
        jsonb_build_array('h3', 'لكل فريقٍ قاعاته'),
        jsonb_build_array('p', 'إلى جانب قاعتي الاجتماعات والتدريب العامّتين، لكل فريقٍ قاعتاه: '
          || 'قاعة اجتماعات الترجمة التخصصية وقاعة تدريبها لا يراهما غير المترجمين المتخصصين، '
          || 'وقاعة اجتماعات الإرشاد المكاني وقاعة تدريبه لا يراهما غير المرشدين. '
          || 'ومدير المشروع ومدير المشروع من الهيئة والمنسقون يرون القاعات كلها ويدخلونها. '
          || 'والحجب في قاعدة البيانات لا في الشاشة وحدها.'));
    end if;

    -- الفريق: صلاحيات الحساب الإداري، وإلزام التحقق، وباب التسجيل، والمرشد المتميّز
    if v_id = 'team' and not (v_blocks::text like '%قائمة صلاحيات%') then
      v_blocks := v_blocks || jsonb_build_array(
        jsonb_build_array('h3', 'قائمة صلاحيات الحساب الإداري'),
        jsonb_build_array('p', 'لكل حسابٍ إداري — منسقًا كان أو مدير مشروع من الهيئة — قائمةُ صلاحيات '
          || 'يضبطها مدير المشروع صلاحيةً صلاحية: إضافة المواد وإسنادها، والاعتماد، وبيانات الأعضاء '
          || 'ووثائقهم وتقييمهم، وبطاقات العمل، والمراسلات الداخلية، والحضور والانصراف، '
          || 'وتقييم المرشدين، والترجمة الفورية، والدليل المصطلحي، والقاعات، والإعدادات المرجعية، '
          || 'ودليل الإنتاج والأرشيف. والأصل فيها كلها الفتح، وما يُغلق يُحجب من القائمة ويُمنع في '
          || 'قاعدة البيانات لا في الشاشة وحدها.'),
        jsonb_build_array('h3', 'التحقق بخطوتين: عامًّا أو لحسابٍ بعينه'),
        jsonb_build_array('p', 'إلى جانب إلزام حسابات الإدارة كلها، يُلزَم حسابٌ بعينه بالتحقق بخطوتين، '
          || 'فلا يدخل حتى يفعّله بتطبيق المصادقة على جهازه. والتفعيل بيد صاحبه وحده، '
          || 'فلا يملكه أحدٌ عنه.'),
        jsonb_build_array('h3', 'باب التسجيل'),
        jsonb_build_array('p', 'يُفتح باب التسجيل مدةً معلومة يحدّدها مدير المشروع ثم يُغلق بنفسه، '
          || 'فلا يبقى مفتوحًا لو انتشر رابطه. ومتى أُغلق لم يُنشأ حسابٌ جديد بأي طريق، '
          || 'ويبقى لمدير المشروع إنشاء الحسابات يدويًّا.'),
        jsonb_build_array('h3', 'المرشد المتميّز'),
        jsonb_build_array('p', 'الأصل في فريق الإرشاد المكاني ألّا تُسنَد إليه أعمال ترجمة. ويُستثنى '
          || 'المتميّز منهم بقرارٍ مكتوب في ملفه، فتُسنَد إليه الترجمة في لغته المسجَّلة وحدها، '
          || 'ولا تُرفع عنه الإتاحة وفي يده عملٌ لم يُنجز.'));
    end if;

    v_new := v_new || jsonb_build_array(jsonb_build_array(v_s -> 0, v_s -> 1, v_blocks));
  end loop;

  v := jsonb_set(v, '{sections}', v_new);
  update public.page_content set content = v, updated_at = now() where key = 'initiative';
end $$;

notify pgrst, 'reload schema';
