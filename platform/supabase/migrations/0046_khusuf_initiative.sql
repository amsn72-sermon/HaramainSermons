-- =====================================================================
-- 0046 — خطبة الخسوف في أنواع الخطب، وتحديث «عن المبادرة» (ملاحظة ١٦٩)
--   ١) نوعٌ جديد: «خطبة خسوف» برمزه في رقم التوثيق، إلى جانب الكسوف.
--   ٢) «عن المبادرة» يُحدَّث بما استجدّ: عدّادات دليل الإنتاج قسمًا قسمًا،
--      وقاعات الاجتماعات والتدريب بروابطها المستورة وإرشادات مستخدميها.
--   ولا يُذكر فيها شيء مالي ولا تسعيرة؛ فذلك شأن داخلي.
-- =====================================================================

-- ---------------------------------------------------------------------
-- ١) خطبة الخسوف — رمزها A، وتزحف بقية الرموز في الترتيب لا في الرمز
-- ---------------------------------------------------------------------
insert into public.doc_type_codes (material_type, sermon_type, code, label, sort) values
  ('خطب', 'خطبة خسوف', 'A', 'خطبة الخسوف', 7)
on conflict (material_type, coalesce(sermon_type, '')) do nothing;

update public.doc_type_codes set sort = sort + 1
 where sermon_type is null and sort >= 7 and material_type <> 'خطب';

-- ---------------------------------------------------------------------
-- ٢) «عن المبادرة»: ما استجدّ
-- ---------------------------------------------------------------------
do $$
declare v jsonb; v_s jsonb; v_id text; v_blocks jsonb; v_new jsonb := '[]'::jsonb;
begin
  select content into v from public.page_content where key = 'initiative';
  if v is null then return; end if;

  for v_s in select jsonb_array_elements(v -> 'sections') loop
    v_id := v_s ->> 0;
    v_blocks := v_s -> 2;

    -- دليل الإنتاج: لكل قسمٍ عدّاداته بوحدته
    if v_id = 'interpretation' and not (v_blocks::text like '%عدّاداته%') then
      v_blocks := v_blocks || jsonb_build_array(
        jsonb_build_array('p', 'ولكل قسمٍ في دليل الإنتاج عدّاداته بوحدته، فلا عدّاد واحد يجمع ما لا يُجمع: '
          || 'الخطب تُعدّ بالمسجدين — الحرام والنبوي — ثم نوعًا نوعًا: الجمعة وعرفة وعيدَي الأضحى والفطر '
          || 'والاستسقاء والكسوف والخسوف. والدروس والندوات والمؤتمرات تُعدّ بساعاتها وبعدد فعالياتها '
          || 'نوعًا نوعًا. والنصوص والكتب والمطويات والمنشورات والتوجيهات تُعدّ بكلماتها وصفحاتها '
          || 'نوعًا نوعًا. والدقائق الصوتية في عدّاداتها المستقلة.'));
    end if;

    v_new := v_new || jsonb_build_array(jsonb_build_array(v_s -> 0, v_s -> 1, v_blocks));

    -- قسمٌ جديد بعد «الفريق»: القاعات واللقاءات
    if v_id = 'team' and not (v::text like '%قاعات الاجتماعات والتدريب%') then
      v_new := v_new || jsonb_build_array(
        jsonb_build_array('rooms', 'قاعات الاجتماعات والتدريب', jsonb_build_array(
          jsonb_build_array('p', 'يجتمع فريق المشروع ويتدرّب داخل المنصة نفسها. والشاشة بابان: '
            || '«قاعة الاجتماعات» لاجتماعات الإدارة والمنسقين ولقاءات العمل، '
            || 'و«قاعة التدريب» للدورات التدريبية وورش العمل. ولكل بابٍ قاعاته، تُضاف القاعة باسمها '
            || 'وسعتها ووصفها.'),
          jsonb_build_array('h3', 'الجدولة والدعوة والانضمام'),
          jsonb_build_array('p', 'يُجدوَل اللقاء بعنوانه ونوعه وقاعته وموعده ومدته وجدول أعماله، '
            || 'ولا تُحجز القاعة الواحدة لقاءين في وقت واحد. ويُختار المدعوّون بأعيانهم أو بمجموعاتهم — '
            || 'الحسابات الإدارية، والمترجمون المتخصصون، والمرشدون المكانيون، ومديرو المشروع من الهيئة — '
            || 'فتصل الدعوة في بريد كل مدعوّ بموعدها ومدتها.'),
          jsonb_build_array('p', 'ويظهر زرّ الدخول للمدعوّ قبل الموعد بربع ساعة، ويبقى حتى نصف ساعة بعد انتهاء '
            || 'اللقاء، ولا يعمل قبل ذلك ولا بعده. ومن لم يُدعَ لا يرى اللقاء أصلًا. '
            || 'ويُقيَّد الحضور تلقائيًّا: من دخل ومتى وكم بقي، ومن لم يحضر — سجلًّا للتدريب '
            || 'ولشهادات الحضور.'),
          jsonb_build_array('h3', 'بابٌ ثابت لا رابطٌ متداوَل'),
          jsonb_build_array('p', 'لكل قاعة رابط جلستها الثابت، يُقترح مميّزًا عند إنشائها ويُعدَّل من إعدادها، '
            || 'ويرثه كل لقاء يُجدوَل فيها ما لم يُخصَّص له رابط. والرابط لا يُعرض في الشاشة ولا يُتداول: '
            || 'الدخول من المنصة وحدها بزرّ «الدخول للقاعة» أو «الدخول للاجتماع»، '
            || 'فلا يدخل الجلسة إلا أهلها. وللقاعة رمزٌ يُمسح بالكاميرا، ويُنزَّل بطاقةً على هوية الهيئة.'),
          jsonb_build_array('h3', 'إرشادات المستخدمين'),
          jsonb_build_array('p', 'وفي الشاشة إرشاداتٌ لمستخدميها، تختلف بين قاعة الاجتماعات وقاعة التدريب: '
            || 'ما قبل اللقاء من تجربة الصوت والصورة ومتى يظهر زرّ الدخول، وآداب الجلسة من كتم الميكروفون '
            || 'وكتابة الاسم الكامل وطلب الكلمة ومشاركة الشاشة، وما بعده من تقييد الحضور، '
            || 'وجدولٌ لما قد يتعثّر وما يُفعل عنده.'),
          jsonb_build_array('p', 'ومجرى الصوت والصورة اليوم من جلسة خارجية، والمنصة تتولى ما لا يتولاه غيرها: '
            || 'الجدولة والدعوة والدخول في وقته وسجلّ الحضور. ومتى صار خادم اللقاءات إلى المنصة '
            || 'صار الدخول فيها نفسها.'))));
    end if;
  end loop;

  v := jsonb_set(v, '{sections}', v_new);
  update public.page_content set content = v, updated_at = now() where key = 'initiative';
end $$;

notify pgrst, 'reload schema';
