-- =====================================================================
-- 0040 — تحديث «عن المبادرة» بما استجدّ (ملاحظة ١٥٣):
--   نسبة المبادرة إلى إدارة المشروع في جامعة أم القرى مرةً واحدة،
--   وإضافة ما أُنجز: البيانات الإلزامية، ومواصفات التسجيل ودليله،
--   وختم التوثيق في صدر العمل، والتسمية الموحّدة، وسجلّ الترجمة الفورية،
--   والدليل المصطلحي، وتسجيل تقييم المرشدين، وحساب مشرف الهيئة،
--   والتصدير المجمَّع على هيئة كتاب.
--   ولا يُذكر فيها شيء مالي ولا تسعيرة؛ فذلك شأن داخلي.
-- =====================================================================

-- ١) نسبة المبادرة: «في جامعة أم القرى» مرةً واحدة في التعريف
update public.page_content
   set content = replace(
         content::text,
         'مبادرة رقمية طوّرتها إدارة مشروع خادم الحرمين الشريفين لترجمة خطب الحرمين الشريفين؛',
         'مبادرة رقمية طوّرتها إدارة مشروع خادم الحرمين الشريفين لترجمة خطب الحرمين الشريفين في جامعة أم القرى؛'
       )::jsonb,
       updated_at = now()
 where key = 'initiative'
   and content::text like '%مبادرة رقمية طوّرتها إدارة مشروع خادم الحرمين الشريفين لترجمة خطب الحرمين الشريفين؛%';

-- ٢) إضافة ما استجدّ إلى أقسام الدليل، وقسمان جديدان
do $$
declare v jsonb; v_s jsonb; v_id text; v_blocks jsonb; v_new jsonb := '[]'::jsonb;
begin
  select content into v from public.page_content where key = 'initiative';
  if v is null then return; end if;

  for v_s in select jsonb_array_elements(v -> 'sections') loop
    v_id := v_s ->> 0;
    v_blocks := v_s -> 2;

    -- اكتمال البيانات ومواصفات التسجيل ودليله والمصطلح الموحَّد
    if v_id = 'quality' and not (v_blocks::text like '%البيانات الرئيسة%') then
      v_blocks := v_blocks || jsonb_build_array(
        jsonb_build_array('h3', 'اكتمال البيانات الرئيسة قبل الإسناد'),
        jsonb_build_array('p', 'لا تُسنَد مادة حتى تكتمل بياناتها الرئيسة: نوعها، ونوع الخطبة، وجهتها، '
          || 'وعنوانها، وتاريخها، واسم خطيبها أو مؤلفها، ونصُّها العربي أو ملف أصلها. '
          || 'ويُنبَّه المنسق على الناقص في الشاشة نفسها، ويُمنع المرور حتى يستوفيه؛ '
          || 'والتحقق نفسه مطبَّق في قاعدة البيانات، فلا تُنشأ مادة ناقصة بأي طريق.'),
        jsonb_build_array('h3', 'مواصفات التسجيل الصوتي ودليله'),
        jsonb_build_array('p', 'تُقبل التسجيلات بالصيغ المعتمدة (WAV أو MP3) دون غيرها، ويُرفض الفيديو. '
          || 'وتُقاس مواصفات كل تسجيل عند رفعه — الصيغة ومعدل العينة والتدفق والقنوات والمدة — '
          || 'وتُعرض للمنسق فيقبل التسجيل أو يعيده إلى صاحبه بملاحظة.'),
        jsonb_build_array('p', 'وفي المنصة دليلٌ للتسجيل الصوتي يُطبع ويُوزَّع: مواصفات التسليم، '
          || 'وآداب التسجيل قبله وأثناءه وبعده، والتسجيل بميكروفون خارجي، '
          || 'وبرامج مجانية مقترحة للآيفون والأندرويد تسجّل بالصيغ المعتمدة.'));
    end if;

    -- ختم التوثيق في صدر العمل
    if v_id = 'docs' and not (v_blocks::text like '%صدر الصفحة الأولى%') then
      v_blocks := v_blocks || jsonb_build_array(
        jsonb_build_array('p', 'ويُطبع الختم في صدر الصفحة الأولى من كل عمل، في الجهة المقابلة لشعار الهيئة: '
          || 'رقم التوثيق، وتحته تاريخ الترجمة بالتقويم الهجري، وإلى جانبه رمز التحقق — '
          || 'في الطباعة وفي ملف Word معًا، ولا يتكرر في بقية الصفحات.'),
        jsonb_build_array('p', 'وتخرج الملفات المسلَّمة بنمط تسمية موحَّد يضبطه مدير المشروع مرة واحدة، '
          || 'يجمع رقم التوثيق ونوع العمل وجهته وتاريخه الهجري ولغته وعنوانه؛ '
          || 'فتتّسق أسماء ملفات الترجمة والتسجيلات وكشوف التصدير، ويسهل أرشفتها واسترجاعها.'));
    end if;

    -- الأرشيف: التصدير المجمَّع على هيئة كتاب
    if v_id = 'archive' and not (v_blocks::text like '%هيئة كتاب%') then
      v_blocks := v_blocks || jsonb_build_array(
        jsonb_build_array('p', 'ويُصدَّر من الأرشيف تجميعٌ على هيئة كتاب: تُختار المدة — شهرًا أو سنةً أو مدةً محددة — '
          || 'ونوع الأعمال واللغات المطلوبة، فيخرج كتابٌ على كليشة الهيئة فيه غلافٌ ببياناته، '
          || 'ثم فهرسٌ بالأعمال وتواريخها وأرقام توثيقها وصفحاتها، ثم كل عمل ببطاقته ونصّه وختمه، '
          || 'بترقيم صفحات متسلسل — ملفًّا لكل لغة أو ملفًّا واحدًا يجمع اللغات.'));
    end if;

    -- الفريق: حساب مشرف الهيئة للاطّلاع
    if v_id = 'team' and not (v_blocks::text like '%مشرف الهيئة%') then
      v_blocks := v_blocks || jsonb_build_array(
        jsonb_build_array('h3', 'حساب مشرف الهيئة — اطّلاعٌ لا تعديل'),
        jsonb_build_array('p', 'يُفتح لمشرفي الهيئة حسابٌ للاطّلاع وحده: يرى دليل الإنتاج وكشوف الإنجاز '
          || 'والأرشيف وسجلّ الترجمة الفورية وتقييم المرشدين، ولا يعدّل شيئًا، '
          || 'ولا يطّلع على بيانات الأعضاء الشخصية ولا على المراسلات الداخلية. '
          || 'ويُقيَّد كل فتحٍ لشاشة في سجلّ اطّلاع يراه مدير المشروع.'));
    end if;

    -- الإرشاد المكاني: تسجيل التقييم الأسبوعي الوارد من مشرفي الهيئة
    if v_id = 'field' and not (v_blocks::text like '%التقييم الأسبوعي%') then
      v_blocks := v_blocks || jsonb_build_array(
        jsonb_build_array('p', 'ويُسجَّل في المنصة التقييم الأسبوعي الوارد من مشرفي الهيئة بمعاييره الخمسة — '
          || 'الزيّ والمظهر، والحضور والانضباط، والتفاعل الميداني، والكفاءة اللغوية، والالتزام بالتوجيهات — '
          || 'مع اسم المشرف وتاريخ تقييمه وملاحظاته، ويُجمع متوسط الشهر لكل مرشد. '
          || 'والمنصة تسجّل التقييم وتعرضه للإدارة، ولا تصدره ولا تبني عليه إجراءً آليًّا.'));
    end if;

    v_new := v_new || jsonb_build_array(jsonb_build_array(v_s -> 0, v_s -> 1, v_blocks));

    -- قسمان جديدان بعد «الأرشيف وكشوف الإنجاز»
    if v_id = 'archive' and not (v::text like '%سجلّ الترجمة الفورية%') then
      v_new := v_new || jsonb_build_array(
        jsonb_build_array('interpretation', 'الترجمة الفورية وسجلّ ساعاتها', jsonb_build_array(
          jsonb_build_array('p', 'إلى جانب الترجمة التحريرية، يترجم أعضاء المشروع فوريًّا في الدروس العلمية '
            || 'والندوات والمؤتمرات بحسب ما تطلبه الهيئة. وتُدوَّن كل فعالية في سجلّ مستقل بعد إتمامها: '
            || 'المترجم ولغته، وتاريخ الفعالية وعدد ساعاتها، ونوعها ومكانها وعنوانها وملقيها، '
            || 'ورابط نشرها إن نُشرت.'),
          jsonb_build_array('p', 'ويُستخرج من السجلّ مجموع الساعات بالشهر أو بالمدة، وبحسب اللغة والمترجم '
            || 'ونوع الفعالية، ويُصدَّر كشفًا يُطبع ويُسلَّم.'),
          jsonb_build_array('p', 'ويعرض دليل الإنتاج الأعمال بوحداتها كما في نطاق المشروع: '
            || 'الخطب بأنواعها بالخطبة — وكل لغة خطبةٌ مستقلة — والدروس والندوات والمؤتمرات بالساعة، '
            || 'والنصوص والكتب والمطويات والمنشورات والتوجيهات بالكلمة؛ فلا تختلط الوحدات في مجموع واحد. '
            || 'وتُوثَّق الدقائق الصوتية في قسم مستقل بكل تسجيل على حدة: عملُه ولغته ومَن رفعه وتاريخُه ومدتُه وحالُه.'))),
        jsonb_build_array('glossary', 'الدليل المصطلحي الشرعي الموحَّد', jsonb_build_array(
          jsonb_build_array('p', 'في المنصة دليلٌ مصطلحي شرعي موحَّد: مصطلحٌ عربي، وشرحٌ مختصر يوضّح معناه الشرعي الصحيح، '
            || 'ومقابله المعتمد في كل لغة، وتصنيفه عقديًّا أو فقهيًّا أو دعويًّا، وحالُ اعتماده ومَن اعتمده.'),
          jsonb_build_array('p', 'ويُبحث فيه من داخل شاشة الترجمة نفسها بلا مغادرة العمل، '
            || 'ويُصدَّر جدولًا للهيئة. والرجوع إليه إلزامي عند لبس المصطلح؛ '
            || 'فلا يختلف المترجمون في لفظٍ شرعي واحد.'))));
    end if;
  end loop;

  v := jsonb_set(v, '{sections}', v_new);
  update public.page_content set content = v, updated_at = now() where key = 'initiative';
end $$;

notify pgrst, 'reload schema';
