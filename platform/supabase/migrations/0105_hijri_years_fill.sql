-- 0105 — تقويمُ الأعوام يُستوفى، فلا يَخفى عامٌ رُفعت خطبُه (إصلاحٌ عاجل)
--
--   جدولُ `hijri_years` (من ٠٠٣٥) كان يحمل ١٤٤٥ إلى ١٤٤٨ فقط، لأنّ
--   حاجتَه يومَها كانت ترقيمَ التوثيق للعام الجاري. ثم جاء أرشيفُ
--   الخطب (٣٠٣) فصار يَحسب أسابيعَ العام من هذا الجدول — فإذا رُفعت
--   خطبُ ١٤٤٤ لم تُعرَف له بدايةٌ، فخلا جدولُ الأسابيع وبدا الأرشيفُ
--   فارغًا، والخطبُ محفوظةٌ لم تَضِع.
--
--   فيُستوفى الجدولُ من ١٤٣٥ إلى ١٤٥٥ بتقويم أم القرى، ويُجعَل
--   للبدايةِ حسابٌ احتياطيٌّ إن سُئل الجدولُ عن عامٍ ليس فيه — فلا
--   تَخلو شاشةٌ بعد اليوم لنقصٍ في مرجعٍ، ويُعاد حسابُ أرقام الأسابيع
--   لما رُفع قبلَ هذا الإصلاح.
-- =====================================================================

