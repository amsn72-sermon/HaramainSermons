-- ---------------------------------------------------------------------
-- ٢) حسابٌ احتياطيٌّ لبداية عامٍ ليس في الجدول
--    التقويمُ الحسابيُّ يقارب أمَّ القرى في يومٍ أو يومَين، وهو خيرٌ
--    من شاشةٍ خالية. وما في الجدول مقدَّمٌ عليه دائمًا.
-- ---------------------------------------------------------------------
create or replace function public.hijri_year_start(p_year int)
returns date language sql stable set search_path = public as $$
  select coalesce(
    (select y.starts_on from public.hijri_years y where y.h_year = p_year),
    date '1970-01-01' + (1 + (p_year - 1) * 354 + ((3 + 11 * p_year) / 30)
                         + 1948438 - 2440587)::int)
$$;
grant execute on function public.hijri_year_start(int) to authenticated;

comment on function public.hijri_year_start(int) is
  'بدايةُ العام الهجري: من الجدول إن كان فيه، وإلا بحسابٍ احتياطي';

-- ---------------------------------------------------------------------
-- ٣) حدودُ العام تُبنى على الحساب الاحتياطي، فلا تعود فارغةً أبدًا
-- ---------------------------------------------------------------------
create or replace function public.hijri_year_bounds(p_year int)
returns table (starts_on date, ends_on date)
language sql stable set search_path = public as $$
  select public.hijri_year_start(p_year),
         public.hijri_year_start(p_year + 1) - 1
$$;
grant execute on function public.hijri_year_bounds(int) to authenticated;

-- ---------------------------------------------------------------------
-- ٤) ما رُفع قبل الإصلاح: يُعاد حسابُ جمعتِه ورقمِ أسبوعه
-- ---------------------------------------------------------------------
update public.arch_sermons s
   set friday_on = public.friday_of(s.sermon_date),
       week_no   = public.arch_week_no(s.h_year, s.sermon_date)
 where s.sermon_date is not null
   and (s.week_no is null or s.friday_on is null
        or s.friday_on <> public.friday_of(s.sermon_date)
        or s.week_no <> public.arch_week_no(s.h_year, s.sermon_date));

