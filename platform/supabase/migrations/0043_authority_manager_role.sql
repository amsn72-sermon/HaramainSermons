comment on type public.app_role
  is 'دور العضو: مدير المشروع · منسق · مترجم · مدير المشروع من الهيئة (اطّلاع فقط)';

comment on function public.is_supervisor()
  is 'مدير المشروع من الهيئة: يرى ولا يكتب (ملاحظتا ١٤٦ و١٦٤)';

comment on table public.supervisor_views
  is 'سجلّ اطّلاع مدير المشروع من الهيئة: أي شاشة فُتحت ومتى (ملاحظة ١٤٦)';

-- يرى الفريق والورديات والبطاقات وميثاق العمل كما يراها المنسق — اطّلاعًا.
-- تُضاف سياسة قراءة مستقلة لهذا الدور، فسياسات الصفوف تُجمع بـ«أو»،
-- ولا نمسّ سياسات قائمة قد تختلف أسماؤها بين النسخ.
do $$
declare t text;
begin
  foreach t in array array['shifts', 'member_cards', 'policy_acceptances', 'shift_crew'] loop
    if to_regclass('public.' || t) is not null then
      execute format('drop policy if exists "authority manager reads" on public.%I', t);
      execute format('create policy "authority manager reads" on public.%I for select using (public.is_supervisor())', t);
    end if;
  end loop;
end $$;

-- صفحة المبادرة: الاسم الجديد ووصف الصلاحية
update public.page_content
   set content = replace(
         replace(content::text,
           'حساب مشرف الهيئة — اطّلاعٌ لا تعديل',
           'حساب مدير المشروع من الهيئة — اطّلاعٌ لا تعديل'),
         'يُفتح لمشرفي الهيئة حسابٌ للاطّلاع وحده: يرى دليل الإنتاج وكشوف الإنجاز والأرشيف وسجلّ الترجمة الفورية وتقييم المرشدين، ولا يعدّل شيئًا، ولا يطّلع على بيانات الأعضاء الشخصية ولا على المراسلات الداخلية. ويُقيَّد كل فتحٍ لشاشة في سجلّ اطّلاع يراه مدير المشروع.',
         'يُفتح لمدير المشروع من طرف الهيئة حسابٌ يرى به ما يراه المنسق: لوحة المتابعة والأرشيف ودليل الإنتاج وسجلّ الترجمة الفورية وفريق العمل وورديات الإرشاد وتقييم المرشدين والقاعات. ولا يعدّل شيئًا ولا يُنشئ، ولا يطّلع على البيانات الشخصية للأعضاء ولا على المراسلات الداخلية. ويُقيَّد كل فتحٍ لشاشة في سجلّ اطّلاع يراه مدير المشروع.'
       )::jsonb,
       updated_at = now()
 where key = 'initiative';

