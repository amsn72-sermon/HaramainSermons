-- =====================================================================
-- 0055 — تحديث «عن المبادرة» بما استجدّ في التحديث الرابع والعشرين
--   (ملاحظات ١٧٨–١٩٢): قاعاتٌ ثلاثٌ لكل بوّابة ومحاورُ الاجتماع ومحضره
--   وأمينُ سرّه والتدريبُ المكرَّر، والتسجيلُ أربعةُ بيانات ثم استكمالٌ
--   يُدقَّق، ومدينةُ المرشد، والمخصَّصون لإجابة السائلين ولا فتوى لأحد،
--   وحمايةُ المرفقات، وضبطُ احتساب الكلمات على الأصل العربي.
--   ولا يُذكر فيها شيء مالي ولا تسعيرة، ولا مكان الاستضافة.
-- =====================================================================

do $$
declare v jsonb; v_s jsonb; v_id text; v_blocks jsonb; v_new jsonb := '[]'::jsonb;
begin
  select content into v from public.page_content where key = 'initiative';
  if v is null then return; end if;

  for v_s in select jsonb_array_elements(v -> 'sections') loop
    v_id := v_s ->> 0;
    v_blocks := v_s -> 2;

    -- ---------------- القاعات: ثلاثٌ لكل بوّابة، ومحضرٌ نموذجي ----------------
    if v_id = 'rooms' and not (v_blocks::text like '%محضر الاجتماع%') then
      v_blocks := v_blocks || jsonb_build_array(
        jsonb_build_array('h3', 'ثلاث قاعاتٍ لكل بوّابة'),
        jsonb_build_array('p', 'تُفتح بوّابتا القاعات والتدريب على ثلاث قاعاتٍ في كلٍّ منهما: '
          || 'قاعةُ الترجمة التخصصية، وقاعةُ الإرشاد المكاني، وقاعةُ الإداريين. '
          || 'ولا يرى العضو إلا قاعة فريقه، ومدير المشروع ومدير المشروع من الهيئة والمنسقون '
          || 'يرون الجميع. وهذه الستُّ قاعاتٌ أصلية: تُعدَّل بياناتها ولا تُحذف.'),
        jsonb_build_array('h3', 'محاور الاجتماع وبنوده'),
        jsonb_build_array('p', 'يضع المنسق قبل الاجتماع محاورَه بنودًا مرقَّمة، لكل بندٍ عنوانه ومن يعرضه '
          || 'وزمنه. وتظهر المحاور للمدعوّين مع الدعوة، فيحضرون على بيانٍ بما يُبحث.'),
        jsonb_build_array('h3', 'أمين سرّ الاجتماع'),
        jsonb_build_array('p', 'يعيّن المنسق لكل اجتماع أمين سرٍّ من مدعوّيه، يكتب المحاور والمحضر. '
          || 'ويبقى الاعتماد النهائي للمنسق ومدير المشروع، فلا يُعتمد محضرٌ إلا منهما.'),
        jsonb_build_array('h3', 'محضر الاجتماع على الصيغة النموذجية'),
        jsonb_build_array('p', 'يُبنى المحضر على المحاور نفسها: بيانات الاجتماع وموعده وقاعته ورئيسه، '
          || 'والحاضرون والغائبون مستخرَجين من سجلّ الدخول لا بالتقدير، ثم لكل محورٍ ما دار فيه '
          || 'وقرارُه ومسؤولُه وتاريخُ استحقاقه، ثم التمهيد والخاتمة وموعد الاجتماع القادم. '
          || 'ويُحفظ مسودةً ثم يُعتمد، ويُطبع على كليشة الهيئة بتوقيعَي أمين السرّ ورئيس الاجتماع.'),
        jsonb_build_array('h3', 'التدريب: جلسةً أو جلسات'),
        jsonb_build_array('p', 'تُجدول الدورة التدريبية جلسةً واحدة أو جلساتٍ متتابعة في الأيام التالية '
          || 'بالموعد والمدة نفسيهما، فتُنشأ جلساتُها مرةً واحدة مرقَّمةً في سلسلةٍ واحدة. '
          || 'ولكل جلسةٍ حضورُها ومحضرُها، ويُرفق بها محتواها التدريبي فيراه المتدربون قبلها.'),
        jsonb_build_array('h3', 'المدعوّ يرى ولا يُعدّل'),
        jsonb_build_array('p', 'يرى المدعوُّ اجتماعه ومحاوره ومحضره قراءةً لا تعديلًا، ويبقى الاجتماع '
          || 'ومحضره ظاهرَين له بعد انقضائه وأرشفته، فلا يُحجب عنه ما حضره — '
          || 'إلا أن يحذفه مدير المشروع. والحذف له وحده، وما عداه من تصرّفٍ في الاجتماع للمنسق.'));
    end if;

    -- ---------------- الفريق: التسجيل والاستكمال، والمدينة، وإجابة السائلين ----------------
    if v_id = 'team' and not (v_blocks::text like '%إجابة السائلين%') then
      v_blocks := v_blocks || jsonb_build_array(
        jsonb_build_array('h3', 'التسجيل أربعةُ بيانات'),
        jsonb_build_array('p', 'لا يُطلب في التسجيل إلا أربعة: الاسم الكامل، والبريد الإلكتروني، '
          || 'ورقم الهوية أو الإقامة، ورقم الجوال. وما سواها يستكمله العضو بعد تفعيل حسابه على مهل، '
          || 'فلا يُحبَس عن التسجيل بجمع ورقٍ في مجلسٍ واحد.'),
        jsonb_build_array('h3', 'استكمال البيانات وتدقيقها'),
        jsonb_build_array('p', 'تظهر للعضو بعد التفعيل بطاقةٌ تبيّن ما بقي عليه: الجنسية ومكان الإقامة '
          || 'ولغاتُه وصورتُه الشخصية وصورةُ هويته. فإذا اكتملت أرسلها للتدقيق، '
          || 'فيقبلها المنسق أو مدير المشروع أو يُعيدها إليه ببيان ما ينقص، ويصله ذلك في إشعار. '
          || 'ولا تُعدُّ بياناتُه معتمدةً حتى تُقبل.'),
        jsonb_build_array('h3', 'مدينة المرشد المكاني'),
        jsonb_build_array('p', 'يحدّد المرشد المكاني عند تسجيله المسجد الذي يرشد فيه: المسجد الحرام أو '
          || 'المسجد النبوي. وعليها تُبنى دعواته، فاجتماعُ أهل مكة لهم، واجتماعُ أهل المدينة لهم، '
          || 'ويُدعى من يُراد منهم بأعيانهم عند الحاجة.'),
        jsonb_build_array('h3', 'المخصَّصون لإجابة السائلين'),
        jsonb_build_array('p', 'قائمةٌ ثالثةٌ في الفريق إلى جانب المترجمين المتخصصين والمرشدين المكانيين. '
          || 'ولا يُسجَّل فيها أحدٌ ابتداءً: إنما ينقل إليها المنسق أو مدير المشروع من يراه أهلًا لها '
          || 'بعد تسجيله ومعرفة لغته.'),
        jsonb_build_array('h3', 'لا فتوى لأحدٍ من الفريق'),
        jsonb_build_array('p', 'ليس لأحدٍ من الفريق — مترجمًا كان أو مرشدًا أو منسقًا — أن يفتي في مسألةٍ '
          || 'شرعية بحال، ولو كان الجواب عنده معلومًا، ولو ألحّ السائل. والواجب نقلُ السؤال إلى أهل '
          || 'الفتوى المعتمدين، ثم نقلُ جوابهم كما هو، لا يُزاد فيه ولا يُنقص ولا يُفسَّر. '
          || 'وهذا بندٌ في ميثاق العمل يوقّعه كلُّ عضو، ومكتوبٌ في بطاقة من خُصّص لإجابة السائلين.'));
    end if;

    -- ---------------- حماية المواد: ما رُفع عن شاشات الأعضاء يُبيَّن هنا ----------------
    if v_id = 'security' and not (v_blocks::text like '%علامة مائية%') then
      v_blocks := v_blocks || jsonb_build_array(
        jsonb_build_array('h3', 'حماية المرفقات والأصول'),
        jsonb_build_array('p', 'تُعرض المرفقات والأصول داخل المنصة عرضًا فقط: لا تنزيل ولا طباعة، '
          || 'وعلى كل صفحةٍ علامةٌ مائية تحمل هوية من يطّلع، ويُقيَّد كلُّ فتحٍ في سجلّ الاطّلاع. '
          || 'وهذا بيانٌ للجهات المختصة عن كيفية الحماية، ولا يُثقَل به العضو في كل شاشة.'));
    end if;

    -- ---------------- المخرجات: الاحتساب على الأصل العربي ----------------
    if v_id = 'outputs' and not (v_blocks::text like '%الأصل العربي%') then
      v_blocks := v_blocks || jsonb_build_array(
        jsonb_build_array('h3', 'ضبط الاحتساب على الأصل العربي'),
        jsonb_build_array('p', 'تُحصى كلماتُ العمل من النص العربي الأصل، لا من الترجمة، وتُحصى مرةً واحدة '
          || 'للمادة لا لكل لغةٍ على حدة. تستخرجها المنصة بنفسها من النص المكتوب ومن ملف PDF، '
          || 'ويصحّحها المنسق متى أخطأت الآلة، فيُحفظ ما أحصته الآلة بجانب المصحَّح للمقارنة. '
          || 'ويُبيَّن في دليل الإنتاج ما لم يُحصَ أصلُه بعد، فلا يبقى ناقصًا بلا علم.'),
        jsonb_build_array('h3', 'وحدات الاحتساب لا تُخلط'),
        jsonb_build_array('p', 'لكل نوعٍ من العمل وحدتُه التي يُقاس بها، ولا تُجمع الوحدات في رقمٍ واحد: '
          || 'الخطب بالخطبة لكل لغة، والنصوص والكتب والمطويات بالكلمة، والدروس والندوات بالساعة، '
          || 'وإجابة السائلين بالحضور من سجلّ الورديات، والإرشاد المكاني بالفرد في الفترة '
          || 'مربوطًا بتقييم مشرفي الهيئة.'));
    end if;

    -- ---------------- سير العمل: نافذة الخطبة ----------------
    if v_id = 'how' and not (v_blocks::text like '%نافذة التسليم%') then
      v_blocks := v_blocks || jsonb_build_array(
        jsonb_build_array('h3', 'نافذة التسليم في الخطبة'),
        jsonb_build_array('p', 'تصل خطبةُ الجمعة في الغالب يوم الثلاثاء أو الأربعاء، ملفًّا أو نصًّا مكتوبًا. '
          || 'فتُحتسب مدد المراحل من النافذة الباقية فعلًا حتى ما قبل الخطبة بساعات أمان، '
          || 'لا من عدد أيامٍ مقطوع. ويُبيَّن للمنسق كم بقي، وينبَّه إن وصلت المادة خارج موعدها '
          || 'المعتاد أو كانت النافذة أقلَّ من يوم، فيعيد النظر في الإسناد والأهمية.'));
    end if;

    v_new := v_new || jsonb_build_array(jsonb_build_array(v_s -> 0, v_s -> 1, v_blocks));
  end loop;

  update public.page_content
     set content = jsonb_set(v, '{sections}', v_new),
         updated_at = now()
   where key = 'initiative';
end $$;

notify pgrst, 'reload schema';
