-- =====================================================================
-- 0060 — اختصارُ صفحة «عن المبادرة» (ملاحظة ١٩٨)
--   الصفحةُ تعريفٌ بالمبادرة لمن يقرؤها من خارجها، وقد دخلها من تفصيل
--   العمل الداخلي ما لا داعيَ له: قوائمُ صلاحيات الحسابات الإدارية، ومن
--   يملك ماذا من مدير المشروع والمنسقين، وإعداداتُ الدخول والتسجيل.
--   وهذا شأنٌ يُضبط في المنصة لا يُعرض في صفحة تعريف.
--
--   فحُذفت ثمانيةُ مواضع كاملة، وأُعيدت صياغةُ ما بقي فيه ذكرُ صلاحيةٍ
--   بصيغةٍ مؤسسية: «تُعتمد» و«تُصحَّح» و«من الإدارة» — فيبقى المعنى
--   ويسقط التفصيل. وحُذف من «القاعات» ما لم يعد مطابقًا للواقع بعد أن
--   صار الدخول في نافذةٍ مستقلة، وما تكرّر مرتين.
-- =====================================================================

do $$
declare
  v        jsonb;
  v_s      jsonb;
  v_id     text;
  v_blocks jsonb;
  v_keep   jsonb;
  v_b      jsonb;
  v_new    jsonb := '[]'::jsonb;
  v_skip   boolean;
  v_title  text;

  -- العناوينُ التي تُحذف هي وما تحتها حتى العنوان التالي
  drop_team text[] := array[
    'حساب مدير المشروع من الهيئة — اطّلاعٌ لا تعديل',
    'قائمة صلاحيات الحساب الإداري',
    'التحقق بخطوتين: عامًّا أو لحسابٍ بعينه',
    'باب التسجيل',
    'التسجيل أربعةُ بيانات',
    'استكمال البيانات وتدقيقها'
  ];
  drop_rooms text[] := array[
    'إرشادات المستخدمين',
    'الدخول من المنصة، والإذن بيد المنسق',
    'ثلاث قاعاتٍ لكل بوّابة'
  ];
  drops text[];
begin
  select content into v from public.page_content where key = 'initiative';
  if v is null then return; end if;

  for v_s in select jsonb_array_elements(v -> 'sections') loop
    v_id     := v_s ->> 0;
    v_title  := v_s ->> 1;
    v_blocks := v_s -> 2;

    drops := case v_id when 'team' then drop_team
                       when 'rooms' then drop_rooms
                       else null end;

    if drops is not null then
      v_keep := '[]'::jsonb;
      v_skip := false;
      for v_b in select jsonb_array_elements(v_blocks) loop
        if (v_b ->> 0) = 'h3' then
          v_skip := (v_b ->> 1) = any (drops);
        end if;
        if not v_skip then v_keep := v_keep || jsonb_build_array(v_b); end if;
      end loop;
      v_blocks := v_keep;
    end if;

    -- «فريق العمل والأدوار والصلاحيات» صار «فريق العمل وأدواره»
    if v_id = 'team' then v_title := 'فريق العمل وأدواره'; end if;

    v_new := v_new || jsonb_build_array(
      jsonb_build_array(to_jsonb(v_id), to_jsonb(v_title), v_blocks));
  end loop;

  update public.page_content
     set content = jsonb_set(v, '{sections}', v_new), updated_at = now()
   where key = 'initiative';
end $$;

