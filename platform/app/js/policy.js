export const FIELD_VERSIONS = { '1.0': F10 };

// ـــ ميثاقُ كلِّ فريق: الميدانُ له ميثاقُه، وسائرُ الفريق على ميثاق
//   المترجمين. ومن كان في الميدان وقَّع ميثاقَه هو لا غير.
export const FIELD_TRACKS = ['field', 'answers'];
export const isFieldTrack = t => FIELD_TRACKS.includes(String(t || ''));

// والحساباتُ الإداريةُ على ميثاق المترجمين ولو كان فريقُها الميدان:
//   فهي تطّلع على المواد قبل نشرها، وبنودُ السرية فيه هي التي تلزمها.
const ADMIN_ROLES = ['manager', 'coordinator'];
export const isFieldMember = profile =>
  isFieldTrack(profile?.track) && !ADMIN_ROLES.includes(String(profile?.role || ''));

export const charterOf = profile => (isFieldMember(profile)
  ? { key: FIELD_KEY, version: FIELD_VERSION, doc: F10 }
  : { key: POLICY_KEY, version: POLICY_VERSION, doc: CUR });

// نصُّ نسخةٍ بعينها من ميثاقٍ بعينه
export const charterDoc = (key, v) => (key === FIELD_KEY
  ? (FIELD_VERSIONS[String(v || '').trim()] || F10)
  : policyOf(v));
export const charterTitle = key => (key === FIELD_KEY ? F10.title : CUR.title);
export const charterVersion = key => (key === FIELD_KEY ? FIELD_VERSION : POLICY_VERSION);

// ـــ النصُّ المسطَّحُ للنسخة: منه تُحسَب بصمةُ sha256 في الخادم
//   (ملاحظة ٤٢٥). وصياغتُه ثابتةٌ لا تتغيَّر بتغيُّر العرض، فالبصمةُ
//   الواحدةُ تدلُّ على نصٍّ واحد.
export function policyPlainText(v = POLICY_VERSION, key = POLICY_KEY) {
  const p = charterDoc(key, v);
  const out = [`${p.title} — النسخة ${v}`, '', p.intro, ''];
  p.sections.forEach(([t, items], i) => {
    out.push(`${i + 1}) ${t}`);
    items.forEach(x => out.push(`- ${x}`));
    out.push('');
  });
  out.push(p.ack);
  return out.join('\n');
}

// بندُ المخالفة بنصِّه في نسخةٍ بعينها: هو المحتجُّ به في وثيقة الإثبات
export function policyBreachClause(v = POLICY_VERSION, key = POLICY_KEY) {
  const p = charterDoc(key, v);
  const sec = p.sections.find(([t]) => t.startsWith('المخالفة'));
  return sec ? sec[1][0] : '';
}
