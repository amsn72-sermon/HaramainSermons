export const POLICY_VERSIONS = { '1.1': V11, '1.2': V12 };

// نسخةٌ بعينها، ومن وقَّع على نسخةٍ لا نُعرض عليه غيرَها
export const policyOf = v => POLICY_VERSIONS[String(v || '').trim()] || POLICY_VERSIONS[POLICY_VERSION];

// الجاريةُ: تبقى الأسماءُ القديمةُ لئلّا تتغيَّر مواضعُ استعمالها
const CUR = POLICY_VERSIONS[POLICY_VERSION];
export const POLICY_TITLE = CUR.title;
export const POLICY_INTRO = CUR.intro;
export const POLICY_SECTIONS = CUR.sections;
export const POLICY_ACK = CUR.ack;

// ـــ النصُّ المسطَّحُ للنسخة: منه تُحسَب بصمةُ sha256 في الخادم
//   (ملاحظة ٤٢٥). وصياغتُه ثابتةٌ لا تتغيَّر بتغيُّر العرض، فالبصمةُ
//   الواحدةُ تدلُّ على نصٍّ واحد.
export function policyPlainText(v = POLICY_VERSION) {
  const p = policyOf(v);
  const out = [`${p.title} — النسخة ${v}`, '', p.intro, ''];
  p.sections.forEach(([t, items], i) => {
    out.push(`${i + 1}) ${t}`);
    items.forEach(x => out.push(`- ${x}`));
    out.push('');
  });
  out.push(p.ack);
  return out.join('\n');
}

// بندُ المخالفة بنصِّه في نسخةٍ بعينها: هو المحتجُّ به في وثيقة الإثبات
export function policyBreachClause(v = POLICY_VERSION) {
  const p = policyOf(v);
  const sec = p.sections.find(([t]) => t.startsWith('المخالفة'));
  return sec ? sec[1][0] : '';
}
