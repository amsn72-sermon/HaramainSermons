// قائمة منسدلة بالجنسيات، مع إبقاء قيمة قديمة غير مدرجة إن وُجدت
export function nationalitySelect(h, current = '', label = 'الجنسية') {
  const sel = h('select', { 'aria-label': label },
    h('option', { value: '' }, '— اختر الجنسية —'),
    NATIONALITIES.map(n => h('option', { value: n }, n)));
  const v = String(current || '').trim();
  if (v && !NATIONALITIES.includes(v)) {
    sel.append(h('option', { value: v }, `${v} (مسجّلة سابقًا)`));
  }
  sel.value = v;
  return sel;
}
